class _Probe(BaseTool):
    name = "probe"
    description = "probe"
    permission_level = "read"
    parameters = {"type": "object", "properties": {"x": {"type": "string"}}}

    def __init__(self, fn=None, **attrs):
        super().__init__()
        self._fn = fn or (lambda **kw: "OK")
        for k, v in attrs.items():
            setattr(self, k, v)

    def run(self, **kwargs):
        return self._fn(**kwargs)


def _tool(name, fn=None, **attrs):
    t = _Probe(fn, **attrs)
    t.name = name
    return t




def _probe(tools, call, pre_approved=True, **over):
    """Run one dispatch and report only what it changed around itself."""
    recorded, trust_writes = [], []
    pre_allowed = {t.name for t in tools} if pre_approved else set()
    base = dict(
        tools={t.name: t for t in tools}, _event_sink=None,
        _allow_once_tools=set(pre_allowed), _noninteractive=True,
        _current_turn_thinking_mode=False, _current_chat_source="web",
        current_session_id="probe-session", _current_user_scope_id=SCOPE,
        _current_user_role="admin", _current_username="tenant", _run_kind="chat",
        _ww_training=False, _active_tools=set(), _turn_ran_progress_tool=False,
        _session_workspace=None, history=[], main_persistence=None,
        _record_tool_used=recorded.append,
        _plan_gate_decision=lambda n, t, tool_args=None: None,
        _working_memory_note_gate=lambda tool_args: None,
        _proactive_reply_gate_decision=lambda n, t, a: None,
        _ask_first_gate_decision=lambda n, t: None,
        get_live_session_subagents=lambda: [], _extract_subagent_goal=lambda a: "",
        model_display_name="probe",
    )
    base.update(over)
    fake = bind_chat_stages(SimpleNamespace(**base))

    env_before = os.environ.get("VAF_SESSION_ID", "<unset>")
    policy = "always" if pre_approved else "ask"
    try:
        with patch("vaf.core.trust.get_tool_policy", return_value=policy), \
             patch("vaf.core.trust.is_trusted_dir", return_value=pre_approved), \
             patch("vaf.core.trust.set_tool_policy",
                   lambda *a: trust_writes.append("set_tool_policy")), \
             patch("vaf.core.trust.mark_trusted_dir",
                   lambda *a: trust_writes.append("mark_trusted_dir")):
            Agent.execute_tool(fake, *call)
        env_after = os.environ.get("VAF_SESSION_ID", "<unset>")
    finally:
        # Never leak the probe's session id into the rest of the suite.
        if env_before == "<unset>":
            os.environ.pop("VAF_SESSION_ID", None)
        else:
            os.environ["VAF_SESSION_ID"] = env_before
    return {
        "env_session_id_written": env_after != env_before,
        "recorded_tool_use": list(recorded),
        "allow_once_added": sorted(fake._allow_once_tools - pre_allowed),
        "active_tools_added": sorted(fake._active_tools),
        "trust_writes": sorted(set(trust_writes)),
    }


def _gate(answer):
    """The interactive gate, answered. The only path that writes the persistent store."""
    dangerous = _tool("probe", permission_level="dangerous")
    with patch("vaf.cli.ui.UI.prompt", return_value=answer), \
         patch("vaf.cli.ui.UI.event", lambda *a, **k: None):
        return _probe([dangerous], ("probe", {}), pre_approved=False,
                      _noninteractive=False, current_session_id=None)


SCENARIOS = {
    "ok": lambda: _probe([_tool("probe")], ("probe", {})),
    "unknown_tool": lambda: _probe([_tool("probe")], ("nope", {})),
    "invalid_args": lambda: _probe([_tool("probe", parameters=_STRICT)], ("probe", {})),
    "policy_admin_only": lambda: _probe([_tool("probe", admin_only=True)], ("probe", {}),
                                        _current_user_role="user"),
    "plan_gate": lambda: _probe(
        [_tool("probe")], ("probe", {}),
        _plan_gate_decision=lambda n, t, tool_args=None: "[PLAN REQUIRED] x"),
    "gate_refused": lambda: _probe([_tool("probe", permission_level="dangerous")],
                                   ("probe", {}), pre_approved=False),
    "dup_guard": lambda: _probe([_tool("coding_agent")], ("coding_agent", {}),
                                get_live_session_subagents=lambda: _LIVE_CODER),
    "search_tools": lambda: _probe(
        [_tool("search_tools",
               lambda **kw: "- write_file: writes a file\n- read_file: reads a file"),
         _tool("write_file"), _tool("read_file")], ("search_tools", {})),
    "gate_allow_always": lambda: _gate("a"),
    "gate_allow_once": lambda: _gate("o"),
}


@pytest.mark.parametrize("scenario", sorted(SIDE_EFFECT_BASELINE))
def test_the_side_effects_of_a_dispatch_are_unchanged(scenario):
    assert scenario in SCENARIOS, f"{scenario} is frozen but has no way to reproduce it"
    assert SCENARIOS[scenario]() == SIDE_EFFECT_BASELINE[scenario]


def test_every_scenario_is_frozen():
    missing = sorted(set(SCENARIOS) - set(SIDE_EFFECT_BASELINE))
    assert not missing, f"scenarios with no frozen result: {missing}"


def test_a_blocked_tool_does_not_count_as_used():
    """The asymmetry, spelled out: recording once at the end of a funnel - the obvious
    shape - would start counting blocked tools as used and change what the router offers
    next turn."""
    for blocked in ("policy_admin_only", "plan_gate", "gate_refused"):
        assert SIDE_EFFECT_BASELINE[blocked]["recorded_tool_use"] == [], blocked
    for used in ("ok", "invalid_args", "unknown_tool"):
        assert SIDE_EFFECT_BASELINE[used]["recorded_tool_use"] != [], used


def test_only_one_path_writes_the_persistent_trust_store():
    """That write outlives the process and is machine-global, so the gate is the riskiest
    piece to move. Any second path acquiring it is a finding, not a detail."""
    writers = sorted(n for n, v in SIDE_EFFECT_BASELINE.items() if v["trust_writes"])
    assert writers == ["gate_allow_always"], writers
    assert SIDE_EFFECT_BASELINE["gate_allow_always"]["trust_writes"] == [
        "mark_trusted_dir", "set_tool_policy"]
    assert SIDE_EFFECT_BASELINE["gate_allow_once"]["trust_writes"] == [], (
        "answering 'once' must stay in memory - persisting it would silently widen a "
        "single approval into a standing one"
    )
