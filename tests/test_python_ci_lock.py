def test_the_target_model_matches_the_runner_images():
    """ubuntu-latest takes manylinux up to glibc 2.39, macos-latest arm64 and universal2 wheels,
    windows-latest win_amd64; a wheel for another processor or a newer glibc never counts."""
    from packaging.utils import parse_wheel_filename

    def fits(target, filename):
        rank = target.tag_priority()
        return any(t in rank for t in parse_wheel_filename(filename)[3])

    linux, mac, win = _t("ubuntu-latest", "3.12"), _t("macos-latest", "3.12"), _t("windows-latest", "3.12")
    assert fits(linux, "a-1-cp312-cp312-manylinux_2_39_x86_64.whl")
    assert fits(linux, "a-1-cp312-cp312-manylinux2014_x86_64.whl")
    assert fits(linux, "a-1-cp39-abi3-manylinux_2_17_x86_64.whl")
    assert not fits(linux, "a-1-cp312-cp312-manylinux_2_40_x86_64.whl")
    assert not fits(linux, "a-1-cp312-cp312-musllinux_1_2_x86_64.whl")
    assert not fits(linux, "a-1-cp311-cp311-manylinux_2_17_x86_64.whl")
    assert fits(mac, "a-1-cp312-cp312-macosx_11_0_arm64.whl")
    assert fits(mac, "a-1-cp312-cp312-macosx_10_13_universal2.whl")
    assert not fits(mac, "a-1-cp312-cp312-macosx_10_13_x86_64.whl")
    assert fits(win, "a-1-cp312-cp312-win_amd64.whl")
    assert not fits(win, "a-1-cp312-cp312-win32.whl")
    assert fits(win, "a-1-py3-none-any.whl")
    # pip prefers the most specific wheel: the cp312 build over the pure one.
