# AC 3: the checker, with PyPI replaced by a stand-in


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _lock(*lines) -> str:
    """A lock in uv's shape; each line is 'name==version' or 'name==version ; marker'."""
    out = ["# This file was autogenerated by uv via the following command:", "#    uv pip compile x"]
    for line in lines:
        pin = line.split(";")[0].strip()
        out += [f"{line} \\", f"    --hash=sha256:{_sha(pin)}", "    # via -r requirements.txt"]
    return "\n".join(out) + "\n"


class _Source:
    """{"name==version": [(wheel filename, requires-python, [Requires-Dist])]}."""

    def __init__(self, releases: dict):
        self.releases = releases

    def files(self, name, version):
        return [{"filename": fn, "url": f"https://files.invalid/{fn}", "requires-python": rp,
                 "core-metadata": True} for fn, rp, _ in self.releases[f"{name}=={version}"]]

    def hashes(self, name, version):
        return {_sha(f"{name}=={version}"): f"{name}-{version}.whl"}

    def requires_dist(self, file):
        for files in self.releases.values():
            for fn, _rp, reqs in files:
                if fn == file["filename"]:
                    return reqs
        raise AssertionError(file)

    def sdist_requires(self, file):
        # The selected sdist's own requirements; None stands for "not static in its PKG-INFO".
        return self.requires_dist(file)


def _run(lock_text: str, releases: dict, targets, requirements=()):
    check = _checker()
    entries = check.parse_lock(lock_text)
    reqs = [Requirement(r) for r in requirements]
    return check.check(entries, reqs, targets, _Source(releases), workers=1)


