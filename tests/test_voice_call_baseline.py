# ── the fake websocket ────────────────────────────────────────────────────────

class FakeWebSocket:
    def __init__(self, frames: List[dict], on_drained=None):
        from fastapi import WebSocketDisconnect
        self._frames = [json.dumps(f) for f in frames]
        self._disconnect = WebSocketDisconnect
        self._on_drained = on_drained   # snapshot hook: runs BEFORE the teardown pop
        self.sent: List[dict] = []
        self.cookies: Dict[str, str] = {}
        self.headers: Dict[str, str] = {}
        self.client = type("C", (), {"host": "127.0.0.1", "port": 1234})()

    async def accept(self):
        return None

    async def close(self, code: int = 1000, reason: str = ""):
        raise AssertionError(f"handshake rejected: {code} {reason}")

    async def receive_text(self) -> str:
        if self._frames:
            return self._frames.pop(0)
        # The registry entry is popped by the disconnect teardown (web_server
        # WebSocketDisconnect handler), so the record snapshot must be taken NOW -
        # after the last scripted frame was fully processed, before the teardown.
        if self._on_drained:
            self._on_drained()
        raise self._disconnect(code=1000)

    async def send_json(self, payload: dict):
        self.sent.append(payload)

    async def send_text(self, payload: str):
        self.sent.append(json.loads(payload))


