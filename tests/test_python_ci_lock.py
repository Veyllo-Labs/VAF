"""Every push, the nightly matrix, the release gate and the local gate install requirements.lock.

The CI test jobs used to install requirements.txt, which resolves the newest release every
range allows, while the local gate ran in a venv of its own history. A fresh upstream release
turned a push red that every local check had passed, three pushes in a row. Now one universal,
hash-pinned lock (``uv pip compile --universal``) is what every gating lane installs, and a
separate scheduled run (ci-latest-deps.yml) installs the newest versions and reports, without
blocking anything.

Pinned here: the lock's command and its oldest Python, the uv metadata override, the install
lines of every gating lane, the required status-check names the branch ruleset knows, the
scheduled run's inability to block, the lock-sync job, the local gate's lock venv, and the
checker (scripts/check_requirements_lock.py) with a stand-in for PyPI.
"""
