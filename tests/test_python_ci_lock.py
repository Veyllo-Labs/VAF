"""Every push, the nightly matrix, the release gate and the local gate install requirements.lock.

The CI test jobs used to install requirements.txt, which resolves the newest release every
range allows, while the local gate ran in a venv of its own history. A fresh upstream release
turned a push red that every local check had passed, three pushes in a row. Now one universal,
hash-pinned lock (``uv pip compile --universal``) is what every gating lane installs, and a
separate scheduled run (ci-latest-deps.yml) installs the newest versions and reports, without
blocking anything.

Pinned here: the lock's command and its oldest Python, the uv metadata override, the install
lines of every gating lane, the required status-check names the branch ruleset knows, the
scheduled run's inability to block, the lock-sync job, the local gate's lock venv, and the
checker (scripts/check_requirements_lock.py) with a stand-in for PyPI.
"""
import hashlib
import importlib.util
import json
import os
import random
import re
import sys
import time
from pathlib import Path

import pytest
import yaml
from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
WF = ROOT / ".github" / "workflows"
LOCK = ROOT / "requirements.lock"

# The branch ruleset requires these contexts by name: "test / build-and-test (<os>, <py>)" and
# "lock-sync". Changing them strands the ruleset until it is edited too.
PUSH_PAIRS = [("ubuntu-latest", "3.10"), ("ubuntu-latest", "3.11"), ("ubuntu-latest", "3.12"),
              ("ubuntu-latest", "3.13"), ("macos-latest", "3.12"), ("windows-latest", "3.12")]


def _checker():
    name = "check_requirements_lock"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / "check_requirements_lock.py")
        module = importlib.util.module_from_spec(spec)
        # dataclasses resolve their module through sys.modules while the class is built.
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def _wf(name: str) -> dict:
    return yaml.safe_load((WF / name).read_text(encoding="utf-8"))


def _on(workflow: dict) -> dict:
    # YAML 1.1 reads the bare key `on` as the boolean True.
    return workflow.get("on", workflow.get(True)) or {}


def _pairs(matrix_json: str) -> list:
    return sorted((c["os"], str(c["python-version"])) for c in json.loads(matrix_json)["include"])


def _oldest_ci_python() -> str:
    versions = set()
    for name in ("ci.yml", "ci-nightly.yml"):
        for job in _wf(name)["jobs"].values():
            matrix = (job.get("with") or {}).get("matrix")
            if matrix:
                versions |= {py for _os, py in _pairs(matrix)}
    return min(versions, key=lambda v: tuple(int(p) for p in v.split(".")))


def _lock_command() -> str:
    return (f"uv pip compile requirements.txt --config-file requirements-lock.toml --universal "
            f"--generate-hashes --python-version {_oldest_ci_python()} -o requirements.lock")


def _runs(job: dict) -> str:
    return "\n".join(step.get("run", "") for step in job.get("steps", []))


