def test_forked_entries_select_by_target_python():
    """numpy is locked twice, one release per Python range; each target takes its own. Without
    the fork, 3.10 has no installable numpy; two unmarked entries apply at once."""
    releases = {
        "numpy==2.2.6": [("numpy-2.2.6-cp310-cp310-manylinux_2_17_x86_64.manylinux2014_x86_64.whl", ">=3.10", [])],
        "numpy==2.4.6": [("numpy-2.4.6-cp312-cp312-manylinux_2_27_x86_64.whl", ">=3.11", []),
                         ("numpy-2.4.6-cp310-cp310-manylinux_2_27_x86_64.whl", ">=3.11", [])],
    }
    targets = [_t("ubuntu-latest", "3.10"), _t("ubuntu-latest", "3.12")]
    forked = _lock("numpy==2.2.6 ; python_full_version < '3.11'",
                   "numpy==2.4.6 ; python_full_version >= '3.11'")
    assert _run(forked, releases, targets)[0] == []
    problems, _ = _run(_lock("numpy==2.4.6"), releases, targets)
    assert problems == ["[ubuntu-latest 3.10] numpy==2.4.6: requires another Python "
                        "(numpy-2.4.6-cp310-cp310-manylinux_2_27_x86_64.whl)"], problems
    problems, _ = _run(_lock("numpy==2.2.6", "numpy==2.4.6"), releases, targets)
    assert any("two entries apply at once" in p for p in problems), problems


