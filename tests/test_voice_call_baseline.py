def _wav(seconds: float, loud: bool) -> bytes:
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(16000)
        n = int(16000 * seconds)
        amp = 12000 if loud else 10
        frames = b"".join(
            struct.pack("<h", amp if (i // 40) % 2 == 0 else -amp) for i in range(n))
        w.writeframes(frames)
    return buf.getvalue()


