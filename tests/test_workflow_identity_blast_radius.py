"""How far the workflow identity switch reaches, measured rather than argued.

Turning ``workflow_identity_injection`` to "declared" changes who a workflow step acts as,
for a lot of tools at once. That is the point - until it flipped, a saved workflow ran as the
machine owner no matter who started it, so its GitHub calls used the ADMIN's token and its
file writes were confined to nobody - but "a lot at once" is exactly the shape of change that
should not rest on somebody's reading of a 47-line if/elif chain.

So the reach is MEASURED here, by EXECUTING the legacy branch for every registered tool and
comparing against what each tool declares. Two things follow:

1. THE SAFETY PROPERTY: no tool may lose an identity key it had before. The switch is meant
   to widen who gets an identity, never to take one away - a tool that silently stopped
   receiving its scope would start writing into the machine owner's data again, which is the
   bug being fixed, reintroduced by its own fix.
2. THE BLAST RADIUS IS A FROZEN FACT. The list below is generated, never typed. It is not
   here to be admired; it is here so that a tool joining or leaving it shows up as a diff in
   a security-relevant review rather than as silence.

The list is a floor, not a ceiling: adding ``identity_kwargs`` to another tool SHOULD extend
it, and the failure message says so. What must not happen is that it changes unnoticed.
"""
import ast
import importlib
import inspect
import pathlib
import pkgutil
import textwrap

from vaf.tools.base import BaseTool

ENGINE = pathlib.Path(__file__).resolve().parents[1] / "vaf" / "workflows" / "engine.py"


def _declared_by_every_tool(include_empty=False):
    import vaf.tools

    out = {}
    for mod in pkgutil.iter_modules(vaf.tools.__path__):
        try:
            module = importlib.import_module("vaf.tools." + mod.name)
        except Exception:
            continue
        for _, cls in inspect.getmembers(module, inspect.isclass):
            if not (issubclass(cls, BaseTool) and cls is not BaseTool):
                continue
            name = getattr(cls, "name", None)
            if not name:
                continue
            keys = tuple(sorted(set(getattr(cls, "identity_kwargs", ()) or ())))
            if keys or include_empty:
                out[name] = keys
    return out


def _legacy_distribution():
    """Run the historical name-list branch for every tool name and record what it assigns.

    EXECUTED rather than parsed. Two attempts to read this by regular expression produced two
    different wrong answers - one merged a nested ``if`` into its parent branch and invented a
    key, the other overwrote a branch and lost one. The function is the only authority on what
    the function does.
    """
    source = ENGINE.read_bytes().decode()
    lines = source.split(chr(10))
    fn = next(n for n in ast.walk(ast.parse(source))
              if isinstance(n, ast.FunctionDef) and n.name == "_inject_user_scope")
    body = textwrap.dedent(chr(10).join(lines[fn.lineno - 1:fn.end_lineno]))
    namespace = {
        "Dict": dict, "Any": object,
        "self": type("_Ctx", (), {"user_scope_id": "SCOPE", "username": "USER"})(),
        "_identity_mode": lambda: "legacy",
        "_identity_is_declared": lambda: False,
        "_inject_declared_identity": lambda name, args: None,
    }
    exec(compile(body, "<legacy-branch>", "exec"), namespace)   # noqa: S102
    inject = namespace["_inject_user_scope"]

    out = {}
    for name in sorted(_declared_by_every_tool(include_empty=True)):
        args = {}
        inject(name, args)
        if args:
            out[name] = tuple(sorted(args))
    return out


