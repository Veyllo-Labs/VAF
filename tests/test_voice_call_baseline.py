def _drive(env, frames: List[dict]) -> FakeWebSocket:
    ws_mod = env["ws_mod"]

    def snap():
        env["record_snapshot"] = _snapshot_record(ws_mod)

    sock = FakeWebSocket(frames, on_drained=snap)
    asyncio.run(ws_mod.websocket_endpoint(sock, token=env["token"]))
    return sock


def _snapshot_record(ws_mod) -> Optional[dict]:
    regs = ws_mod._VOICE_CALLS
    if not regs:
        return None
    rec = list(regs.values())[0]
    return {
        # Length is pinned only where truncation can bite (>= 100 chars): the short
        # vocab-picked lines (greeting, clarify, reask) vary in length per pick -
        # freezing their exact length froze the dice, found when the recheck
        # scenario diverged between two runs of the SAME code (measurement bug #1
        # of this baseline, same class as the five the dispatch baselines caught).
        "history": [(h["role"], len(h["content"]) if len(h["content"]) >= 100
                     else "short") for h in rec.get("history", [])],
        "pending_q": bool(rec.get("pending_q")),
        "pending_speaker_check": bool(rec.get("pending_speaker_check")),
        "chime_recent": len(rec.get("chime_recent", [])),
        "engage_guests": bool(rec.get("engage_guests")),
        "last_self_ts": rec.get("last_self_ts") is not None,
    }


def _voice_sends(sock: FakeWebSocket) -> List[dict]:
    return [p for p in sock.sent
            if str(p.get("type", "")).startswith(("voice_", "speaker_enroll_tts"))]


def _shape(p: dict) -> tuple:
    """A payload's SHAPE: type, sorted keys, the variant flags that are True,
    audio presence - never wording."""
    flags = tuple(sorted(k for k in ("clarify", "reask", "chime_in", "silent",
                                     "greeting") if p.get(k)))
    return (p.get("type"), tuple(sorted(p.keys())), flags,
            p.get("error"), ("audio" in p and p.get("audio") is not None))


def _record(env) -> Optional[dict]:
    return env.get("record_snapshot")


