def _checker():
    name = "check_requirements_lock"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / "check_requirements_lock.py")
        module = importlib.util.module_from_spec(spec)
        # dataclasses resolve their module through sys.modules while the class is built.
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def _wf(name: str) -> dict:
    return yaml.safe_load((WF / name).read_text(encoding="utf-8"))


def _on(workflow: dict) -> dict:
    # YAML 1.1 reads the bare key `on` as the boolean True.
    return workflow.get("on", workflow.get(True)) or {}


def _pairs(matrix_json: str) -> list:
    return sorted((c["os"], str(c["python-version"])) for c in json.loads(matrix_json)["include"])


def _oldest_ci_python() -> str:
    versions = set()
    for name in ("ci.yml", "ci-nightly.yml"):
        for job in _wf(name)["jobs"].values():
            matrix = (job.get("with") or {}).get("matrix")
            if matrix:
                versions |= {py for _os, py in _pairs(matrix)}
    return min(versions, key=lambda v: tuple(int(p) for p in v.split(".")))


def _lock_command() -> str:
    return (f"uv pip compile requirements.txt --config-file requirements-lock.toml --universal "
            f"--generate-hashes --python-version {_oldest_ci_python()} -o requirements.lock")


def _runs(job: dict) -> str:
    return "\n".join(step.get("run", "") for step in job.get("steps", []))


