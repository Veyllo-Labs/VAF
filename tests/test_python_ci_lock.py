_ATOMS = ("python_full_version >= '3.11'", "python_full_version < '3.11'",
          "python_full_version == '3.11.*'", "sys_platform == 'win32'", "sys_platform != 'win32'",
          "sys_platform == 'darwin'", "platform_system == 'Darwin'", "platform_system != 'Windows'",
          "platform_python_implementation != 'PyPy'", "platform_release >= '20.0'")


def _gen_marker(rng, depth=0) -> str:
    if depth >= 2 or rng.random() < 0.4:
        return rng.choice(_ATOMS)
    parts = [_gen_marker(rng, depth + 1) for _ in range(rng.randint(2, 3))]
    text = rng.choice((" and ", " or ")).join(parts)
    return f"({text})" if depth and rng.random() < 0.7 else text


def _gen_name(rng) -> str:
    alnum = "abcdefghijklmnopqrstuvwxyz0123456789"
    parts = ["".join(rng.choice(alnum) for _ in range(rng.randint(1, 6))) for _ in range(rng.randint(1, 3))]
    out = parts[0]
    for p in parts[1:]:
        out += rng.choice("-_.") + p
    return "".join(c.upper() if rng.random() < 0.1 else c for c in out)


def _gen_version(rng) -> str:
    v = ".".join(str(rng.randint(0, 40)) for _ in range(rng.randint(1, 4)))
    return v + rng.choice(("", "", "", "rc1", ".post2", "a3", ".dev4"))


def _gen_lock(rng):
    """(text, [(canonical name, version, extras, marker or None, hashes, requirement text)])."""
    lines = ["# This file was autogenerated by uv via the following command:",
             "#    uv pip compile requirements.txt --universal -o requirements.lock"]
    expected = []
    for _ in range(rng.randint(0, 30)):
        names = [_gen_name(rng)]
        if rng.random() < 0.2:
            names.append(names[0])  # a forked entry
        for name in names:
            version = _gen_version(rng)
            extras = sorted({_gen_name(rng).replace(".", "").replace("_", "").replace("-", "") or "x"
                             for _ in range(rng.randint(0, 2))})
            marker = _gen_marker(rng) if rng.random() < 0.6 else None
            req = name + (f"[{','.join(extras)}]" if extras else "") + f"=={version}"
            if marker:
                req += f" ; {marker}"
            hashes = ["".join(rng.choice("0123456789abcdef") for _ in range(64))
                      for _ in range(rng.randint(1, 40))]
            lines.append(req + " \\")
            pad = " " * rng.randint(1, 8)
            lines += [f"{pad}--hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "")
                      for i, h in enumerate(hashes)]
            if rng.random() < 0.7:
                lines += ["    # via", "    #   -r requirements.txt", f"    #   {_gen_name(rng)}"]
            expected.append((canonicalize_name(name), version, frozenset(extras), marker,
                             frozenset(hashes), req))
    newline = "\r\n" if rng.random() < 0.2 else "\n"
    return newline.join(lines) + newline, expected


def test_the_lock_parser_round_trips_generated_locks():
    """Seeded fuzz of parse_lock against the generator's own entry list, and every entry's
    requirement text against packaging's parser. VAF_LOCK_FUZZ_DRAWS raises the draw count
    outside the suite. Bound: the real lock parses in under a second, the run in under ten."""
    check = _checker()
    started = time.monotonic()
    real = check.parse_lock(LOCK.read_bytes().decode("utf-8"))
    assert time.monotonic() - started < 1.0 and len(real) > 300
    draws = int(os.environ.get("VAF_LOCK_FUZZ_DRAWS", "200"))
    rng = random.Random(393)
    started = time.monotonic()
    for draw in range(draws):
        text, expected = _gen_lock(rng)
        got = check.parse_lock(text)
        assert len(got) == len(expected), (draw, text[:400])
        for entry, (name, version, extras, marker, hashes, req) in zip(got, expected):
            assert (entry.name, entry.version, entry.extras, entry.hashes) == (name, version, extras, hashes), draw
            assert (str(entry.marker) if entry.marker else None) == (str(Marker(marker)) if marker else None), draw
            assert str(Requirement(entry.requirement)) == str(Requirement(req)), draw
    if draws <= 200:
        assert time.monotonic() - started < 10.0
