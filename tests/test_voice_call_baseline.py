def _scenario(env, name):
    """Configure env per scenario; returns the frame script."""
    if name == "normal_reply":
        return [START, _turn()]
    if name == "bad_format":
        return [START, {"type": "voice_call_turn", "audio": "", "format": "wav",
                        "sessionId": ""}]
    if name == "noise_gated":
        return [START, _turn(audio=NOISE_WAV)]
    if name == "stt_empty":
        env["stt_text"] = ""
        return [START, _turn()]
    if name == "busy_local_flag":
        env["exclusive"] = True
        return [START, _turn(main_busy=True)]
    if name == "busy_local_subagent":
        env["exclusive"] = True
        env["subagents"] = [{"task_id": "t1"}]
        return [START, _turn()]
    if name == "llm_failed":
        env["reply"] = None
        return [START, _turn()]
    if name == "model_silence":
        env["reply"] = {"reply": "<silent/>", "delegate": None, "silent": True}
        return [START, _turn()]
    if name == "delegation":
        env["reply"] = {"reply": "Mach ich!", "delegate": "wetter pruefen",
                        "silent": False}
        return [START, _turn(sessionId="")]
    if name == "guest_side_talk_silent":
        env["speaker_enabled"] = True
        env["profile"] = {"name": "Alice"}
        env["score"] = {"score": 0.2, "label": "other", "name": None}
        env["stt_text"] = "wir gehen dann gleich einkaufen ja"
        return [START, _turn()]
    if name == "chime_in":
        env["speaker_enabled"] = True
        env["profile"] = {"name": "Alice"}
        env["score"] = {"score": 0.2, "label": "other", "name": None}
        env["stt_text"] = "wir gehen dann gleich einkaufen ja"
        env["chime_decision"] = {"speak": True, "mode": "quiet", "scene": "multi",
                                 "score": 0.9, "interesting": True, "trigger": None}
        env["chime"] = "Interessant!"
        return [START, _turn()]
    if name == "addressee_clarify":
        env["speaker_enabled"] = True
        env["profile"] = {"name": "Alice"}
        env["score"] = {"score": 0.2, "label": "other", "name": None}
        env["stt_text"] = "kannst du mich hoeren"
        return [START, _turn()]
    if name == "recheck_unsure_directed":
        env["speaker_enabled"] = True
        env["profile"] = {"name": "Alice"}
        env["score"] = {"score": 0.5, "label": "unsure", "name": None}
        env["stt_text"] = "kannst du bitte antworten"
        return [START, _turn()]
    if name == "second_start_resets":
        return [START, _turn(), START]
    raise KeyError(name)


SCENARIOS = ["normal_reply", "bad_format", "noise_gated", "stt_empty",
             "busy_local_flag", "busy_local_subagent", "llm_failed",
             "model_silence", "delegation", "guest_side_talk_silent",
             "chime_in", "addressee_clarify", "recheck_unsure_directed",
             "second_start_resets"]


def _measure(env, name) -> dict:
    env["ws_mod"]._VOICE_CALLS.clear()
    frames = _scenario(env, name)
    sock = _drive(env, frames)
    return {
        "sends": [_shape(p) for p in _voice_sends(sock)],
        "record": _record(env),
        "tq": [{"session_id": c["session_id"],
                "metadata_keys": tuple(sorted((c.get("metadata") or {}).keys()))}
               for c in env["tq_calls"]],
        "confirms": len(env["confirm_calls"]),
    }


@pytest.mark.parametrize("name", SCENARIOS)
def test_the_voice_branch_matches_its_baseline(voice_env, name):
    measured = _measure(voice_env, name)
    assert measured == VOICE_BASELINE[name], (
        f"scenario {name!r} diverged from the frozen measurement - either the "
        f"extraction changed behavior (fix it) or a deliberate change needs a "
        f"REGENERATED baseline with the reason in the commit message"
    )
