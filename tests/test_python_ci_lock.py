@pytest.mark.skipif(sys.version_info < (3, 11), reason="tomllib requires Python 3.11+")
def test_every_metadata_override_matches_a_locked_release():
    """requirements-lock.toml restates sherpa-onnx's requirement on sherpa-onnx-core (a few of
    its wheels declare none, and uv's universal resolution then dropped the core from the
    lock). An override for a release the lock no longer pins is stale, and every requirement
    it names must be locked at a version that satisfies it. MUTATION: bump the lock's
    sherpa-onnx pin and leave the override, or drop the sherpa-onnx-core entry - red."""
    import tomllib

    check = _checker()
    config = tomllib.loads((ROOT / "requirements-lock.toml").read_text(encoding="utf-8"))
    overrides = config.get("dependency-metadata", [])
    assert any(o["name"] == "sherpa-onnx" for o in overrides)
    entries = check.parse_lock(LOCK.read_bytes().decode("utf-8"))
    pins: dict = {}
    for e in entries:
        pins.setdefault(e.name, set()).add(e.version)
    for o in overrides:
        name = canonicalize_name(o["name"])
        assert o["version"] in pins.get(name, set()), (
            f"requirements-lock.toml overrides {name} {o['version']}, the lock pins {pins.get(name)}")
        for line in o.get("requires-dist", []):
            req = Requirement(line)
            have = pins.get(canonicalize_name(req.name), set())
            assert any(req.specifier.contains(v, prereleases=True) for v in have), (
                f"{name} {o['version']} requires {line}; the lock has {sorted(have) or 'nothing'}")


def test_every_requirement_is_locked_for_every_ci_target():
    """Offline half of the checker: on every OS and Python of the matrices, at most one entry
    per package applies, and every requirements.txt line whose marker applies is locked at a
    satisfying version. MUTATION: drop the pyobjc-framework-cocoa entry from the lock - red on
    every macOS target."""
    check = _checker()
    entries = check.parse_lock(LOCK.read_bytes().decode("utf-8"))
    targets = check.matrix_targets()
    assert len(targets) == 12
    problems = []
    for target in targets:
        env = target.env()
        chosen = {}
        for e in entries:
            if e.applies(env):
                assert e.name not in chosen, f"{target.label}: {e.name} applies twice"
                chosen[e.name] = e
        for req in check.top_level():
            if req.marker and not req.marker.evaluate({**env, "extra": ""}):
                continue
            have = chosen.get(canonicalize_name(req.name))
            if have is None or not req.specifier.contains(have.version, prereleases=True):
                problems.append(f"{target.label}: {req} -> {have}")
    assert not problems, problems


