IDENTITY_KEYS = {"user_scope_id", "username", "user_role"}
PLUMBING_KEYS = {"_agent", "_session_id", "session_id", "_session_workspace",
                 "_is_channel_session", "with_vaf_tools"}


def _stub_for(orig):
    """A tool that records instead of acting, wearing the real one's declarations.

    The schema matters: `repair_tool_input` rejects a call with missing required fields
    BEFORE the injection stage, so a stub with an empty schema would measure nothing.
    """
    class _Stub(BaseTool):
        name = orig.name
        description = getattr(orig, "description", "stub")
        parameters = getattr(orig, "parameters", {"type": "object", "properties": {}})
        identity_kwargs = getattr(orig, "identity_kwargs", ())
        permission_level = getattr(orig, "permission_level", "read")
        admin_only = getattr(orig, "admin_only", False)
        channel_restrictions = getattr(orig, "channel_restrictions", ())
        input_aliases = getattr(orig, "input_aliases", {})

        def __init__(self):
            super().__init__()
            self.seen = None

        def run(self, **kwargs):
            self.seen = dict(kwargs)
            return "STUB_OK"

    return _Stub()


def _required_args(schema):
    """Plausible values for the required fields, so the call reaches the injection stage."""
    schema = schema or {}
    props = schema.get("properties") or {}
    out = {}
    for field in schema.get("required") or []:
        spec = props.get(field) or {}
        t = spec.get("type")
        if isinstance(t, list):
            t = t[0]
        if spec.get("enum"):
            out[field] = spec["enum"][0]
        elif t == "integer":
            out[field] = 1
        elif t == "number":
            out[field] = 1.0
        elif t == "boolean":
            out[field] = False
        elif t == "array":
            out[field] = []
        elif t == "object":
            out[field] = {}
        else:
            out[field] = "probe"
    return out




