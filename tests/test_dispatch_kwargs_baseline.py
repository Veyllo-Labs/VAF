"""Frozen record of every kwarg the dispatcher hands each tool, measured before the split.

`Agent.execute_tool` is about to be cut in two: the pipeline (policy, gate, repair, identity,
bounded execution, events) moves to a caller-agnostic funnel so the workflow engine, the
librarian and the coder stop reimplementing it, while the chat-turn machinery (the four
gates, the sub-agent prewrite, the python_exec fallback) stays behind in the agent. That is a
large move of code with side effects, and "nothing changed" is worthless as a claim. This is
the measurement it has to survive.

WHAT IS PINNED. Per tool, the exact set of keys the dispatcher ADDS to the model's arguments -
identity (`user_scope_id`, `username`, `user_role`) and plumbing (`_agent`, `_session_id`,
`session_id`, `_session_workspace`, `_is_channel_session`) alike. Both directions are
failures: one key fewer and a tool silently loses its scope or its bridge to the agent; one
more and a tool starts branching on a value it never had, or writes into the session
workspace instead of where it used to.

HOW IT WAS BUILT. Generated by measurement, never typed. The same list was typed by hand once
during the identity-declaration round and the guard immediately caught nine invented entries
and five missing ones; a hand-written baseline pins the author's belief, not the behaviour.

WHY A FAKE AGENT. Constructing a real `Agent` loads config, resolves a model and builds an
HTTP backend - too slow and too network-dependent for CI. So the guard drives a
`SimpleNamespace`. That is only trustworthy if it answers like the real thing, so the fake was
run against a real `Agent` over all 117 registered tools: 117 measured, 0 differences. When
the fake stops mirroring the dispatcher it will show up here as a diff, not as a silent pass.

THE CONTEXT IS PART OF THE MEASUREMENT. Several branches are conditional, so the numbers only
mean something for one fixed situation: a web (non-channel) chat turn, run kind "chat", an
admin role (so `admin_only` tools reach the injection stage instead of being blocked before
it), no session id, and every tool pre-approved past the confirmation gate. `ask_user` is the
one tool whose identity injection is conditional on the run kind - see
tests/test_identity_kwargs_declaration.py, which pins that separately.
"""
