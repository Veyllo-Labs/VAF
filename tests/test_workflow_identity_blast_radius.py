def test_no_tool_loses_an_identity_key():
    """THE safety property. Widening who receives an identity must never narrow it for
    someone: a tool that stopped receiving its scope would resume writing into the machine
    owner's data, which is the very bug this switch exists to fix."""
    legacy = _legacy_distribution()
    declared = _declared_by_every_tool()
    lost = {name: sorted(set(keys) - set(declared.get(name, ())))
            for name, keys in legacy.items()
            if set(keys) - set(declared.get(name, ()))}
    assert lost == {}, (
        "switching to declared identity would take keys away from these tools; add the "
        "missing key to each tool's identity_kwargs: " + repr(lost)
    )


def test_the_tools_that_gain_an_identity_are_the_ones_recorded():
    """The blast radius. A tool joining this set gains a scope, a role or an owner in every
    workflow step that calls it - that is a security-relevant change and belongs in a diff."""
    legacy = _legacy_distribution()
    declared = _declared_by_every_tool()
    gained = {name: keys for name, keys in declared.items() if name not in legacy}
    added = sorted(set(gained) - set(NEWLY_IDENTIFIED))
    removed = sorted(set(NEWLY_IDENTIFIED) - set(gained))
    assert not added, (
        "these tools now receive an identity in workflows and did not before. That is "
        "usually correct - it is what declaring identity_kwargs means - but it must be a "
        "deliberate line in a diff, so add them here: " + repr(added)
    )
    assert not removed, (
        "these tools stopped gaining an identity. Either they joined the legacy name list "
        "(fine, remove them here) or they lost their declaration (not fine): " + repr(removed)
    )
    differing = {n: (NEWLY_IDENTIFIED[n], gained[n]) for n in gained
                 if n in NEWLY_IDENTIFIED and tuple(gained[n]) != tuple(NEWLY_IDENTIFIED[n])}
    assert not differing, "the keys these tools gain changed: " + repr(differing)


def test_the_switch_reaches_the_file_tools():
    """Named separately because it is the half with teeth: without a scope AND a role the
    per-user file jail cannot form, so before this switch a workflow step could write
    anywhere the machine owner could."""
    for tool in ("read_file", "write_file", "edit_file", "list_files", "tree"):
        assert NEWLY_IDENTIFIED.get(tool) == ("user_role", "user_scope_id"), (
            tool + " no longer gains both halves of the jail identity in workflows"
        )


def test_the_switch_reaches_the_github_tools():
    """The cross-user credential half: token resolution keys on the username, so every
    workflow used to reach for the ADMIN's token whoever started it."""
    github = [n for n in NEWLY_IDENTIFIED if n.startswith("github_")]
    assert len(github) >= 10
    for tool in github:
        assert "username" in NEWLY_IDENTIFIED[tool], tool + " would still resolve a token as admin"
