def _all_tool_classes():
    import importlib
    import inspect
    import pkgutil

    import vaf.core
    import vaf.tools
    seen = {}
    for pkg in (vaf.tools, vaf.core):
        for m in pkgutil.iter_modules(pkg.__path__, pkg.__name__ + "."):
            try:
                mod = importlib.import_module(m.name)
            except Exception:
                continue
            for _, obj in inspect.getmembers(mod, inspect.isclass):
                if issubclass(obj, BaseTool) and obj is not BaseTool and getattr(obj, "name", None):
                    seen[obj.name] = obj
    return seen


TOOL_CLASSES = _all_tool_classes()


def _measure(tool_name, context):
    cls = TOOL_CLASSES[tool_name]
    stub = _stub_for(cls)
    model_args = _required_args(getattr(cls, "parameters", None))
    fake = _fake_agent({tool_name: stub}, thinking=(context == "thinking"))
    with patch("vaf.core.trust.get_tool_policy", return_value="always"), \
         patch("vaf.core.trust.is_trusted_dir", return_value=True):
        result = Agent.execute_tool(fake, tool_name, dict(model_args))
    assert stub.seen is not None, f"{tool_name} never ran; dispatcher returned {result[:120]!r}"
    return sorted(set(stub.seen) - set(model_args))


@pytest.mark.parametrize("tool_name", sorted(KWARGS_BASELINE))
def test_each_tool_still_receives_exactly_what_it_received_before(tool_name):
    """THE guard. Run per tool so a failure names the tool instead of dumping 117 rows."""
    if tool_name not in TOOL_CLASSES:
        pytest.fail(f"{tool_name} no longer resolves to a tool class")
    context, expected = KWARGS_BASELINE[tool_name]
    assert _measure(tool_name, context) == sorted(expected)


def test_no_tool_appeared_that_the_baseline_does_not_know():
    """A new tool is fine, but it must be measured into the baseline deliberately - otherwise
    the guard silently stops covering it."""
    known = set(KWARGS_BASELINE)
    missing = sorted(set(TOOL_CLASSES) - known)
    assert not missing, (
        f"tools with no baseline entry: {missing}. Measure them and add the rows; do not "
        f"type them."
    )


def test_the_baseline_only_contains_keys_the_dispatcher_can_actually_supply():
    """Catches a typo in the frozen literal itself - a misspelled key would make the row
    unfalsifiable, since the dispatcher would never produce it either."""
    allowed = IDENTITY_KEYS | PLUMBING_KEYS
    bad = {n: sorted(set(v) - allowed) for n, (_c, v) in KWARGS_BASELINE.items()
           if set(v) - allowed}
    assert not bad, f"baseline names keys the dispatcher never injects: {bad}"


def test_the_plumbing_split_is_visible_and_not_empty():
    """The split this refactor turns on: identity is declarative already, plumbing is still a
    hardcoded name cascade. If plumbing ever measures empty, the harness stopped reaching the
    cascade and every row above became vacuously true."""
    plumbed = {n for n, (_c, v) in KWARGS_BASELINE.items() if set(v) & PLUMBING_KEYS}
    identified = {n for n, (_c, v) in KWARGS_BASELINE.items() if set(v) & IDENTITY_KEYS}
    assert plumbed, "no tool receives plumbing - the harness is not reaching the cascade"
    assert identified, "no tool receives identity - the harness is not reaching the injection"
