"""Frozen record of what one dispatch CHANGES outside its return value.

Third and last of the baselines taken before `execute_tool` is split. The first covers
what reaches a tool, the second what is emitted and returned. This one covers the writes:
process environment, the persistent trust store, the turn's allow-once set, and the router's
tool sets. They are the part of a refactor nobody diffs, because they are invisible in the
result.

Not measured here, and named so the list does not read as complete: a dispatch also appends
one line to `tool_use_<date>.log` (`ToolCaller._audit_log`, pinned by
tests/test_tool_use_audit_log.py). Files in the log directory were outside this baseline
when it was frozen, and widening a frozen measurement after the fact would make it a record
of two different moments.

WHAT THIS IS REALLY FOR - the asymmetry of `_record_tool_used`. There are 23 `return`
statements before the recording line, so a dispatch that ends early never updates the
router's recency. Measured, that is not arbitrary:

    recorded      ok, invalid_args, unknown_tool, dup_guard, search_tools, both gate accepts
    NOT recorded  a policy block, the plan gate, a refused confirmation

So an argument error counts as "the model tried this tool" while a policy block does not.
Whether or not that is the ideal rule, it is the current one, and a funnel that records once
at the end - the obvious shape - would silently start counting blocked tools as used, which
changes what the router offers on the next turn. Nothing about that shows up in a test that
only checks return values.

THE OTHER THREE:

- `os.environ["VAF_SESSION_ID"]` is written on NO path any more, and the baseline records
  that as False everywhere. It used to be written on every path that resolved a session
  id, including blocked ones, because the write happened before policy ran. The
  justification recorded here - "the workflow CLI subprocess READS this variable, which is
  why it must stay in the chat wrapper" - was already stale when it was written: the
  workflow spawn puts the id into the CHILD's env explicitly (`agent.py`, "not the
  parent's global env"), and `Platform.open_new_terminal` merges that over
  `os.environ.copy()`, so the explicit value wins. Meanwhile the parent-side write was a
  process-global mutation that nothing restored, in a process where the chat worker,
  thinking and the automation scheduler all dispatch tools on their own threads. A lane
  that needs the session now asks `subagent_ipc.get_current_session_id()`, which answers
  per context.
- The trust store is written on exactly one path: accepting a gate with "always"
  (`mark_trusted_dir` + `set_tool_policy`). That write outlives the process and is
  machine-global, so moving the gate is the single riskiest step of the split.
- `_allow_once_tools` grows only on the "once" answer, and `_active_tools` only through the
  search_tools post-hook - which parses one tool per line, name before the colon, and
  silently yields nothing for any other shape.

Measured, never typed. Five measurement bugs were caught and fixed while building these
baselines rather than frozen into them; the search_tools output format was the last of them.
"""
